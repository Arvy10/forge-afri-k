-- Tâches habituelles de chaque rôle (formulées de façon générale : ni heures, ni noms).
-- Elles servent de guide dans « Mon espace » et peuvent être ajoutées d'un clic à ses tâches.
create table if not exists public.pc_role_tasks (
  id          uuid primary key default gen_random_uuid(),
  role_id     uuid not null references public.pc_roles (id) on delete cascade,
  titre       text not null check (char_length(btrim(titre)) between 1 and 200),
  ordre       integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (role_id, titre)
);
create index if not exists pc_role_tasks_role_idx on public.pc_role_tasks (role_id, ordre);
create or replace trigger pc_role_tasks_updated before update on public.pc_role_tasks
  for each row execute function public.pc_set_updated_at();

alter table public.pc_role_tasks enable row level security;
revoke all on public.pc_role_tasks from anon, authenticated;

